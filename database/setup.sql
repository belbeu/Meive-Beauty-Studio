-- =====================================================
-- Meive Beauty Studio - criação completa do banco (PostgreSQL)
--
-- Cria as tabelas, carrega os serviços e (se existir) libera as permissões
-- para o usuário da aplicação local (app_meive).
--
-- Como rodar (veja o README.md):
--   1. Crie o banco e o usuário app_meive (README, passo 2A)
--   2. psql -U postgres -h 127.0.0.1 -d meive_beauty -f database/setup.sql
--
-- Rode UMA vez em um banco vazio. Para recomeçar, apague o banco
-- e crie de novo.
-- =====================================================

-- -----------------------------------------------------
-- Tabelas
-- -----------------------------------------------------

CREATE TABLE usuario (
    id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN ('ADMIN', 'FUNCIONARIA', 'ALUNA', 'CLIENTE')),
    telefone VARCHAR(20),
    criado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    last_login TIMESTAMPTZ
);

CREATE TABLE servico (
    id_servico INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    tecnica VARCHAR(150),
    categoria VARCHAR(100),
    descricao TEXT,
    tag VARCHAR(50),
    -- preco e duracao_minutos aceitam NULL (ex.: "Teste alérgico" = Consultar)
    preco NUMERIC(10,2)
        CHECK (preco >= 0),
    preco_manutencao NUMERIC(10,2)
        CHECK (preco_manutencao >= 0),
    duracao_minutos INT
        CHECK (duracao_minutos > 0)
);

CREATE TABLE agendamento (
    id_agendamento INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_servico INT NOT NULL,
    status VARCHAR(50) NOT NULL,
    data_agendamento TIMESTAMP NOT NULL,
    valor NUMERIC(10,2) CHECK (preco >= 0),
    sinal_pago NUMERIC(10,2) DEFAULT 0.00 CHECK (sinal_pago >= 0),

    CONSTRAINT fk_agendamento_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_agendamento_servico
        FOREIGN KEY (id_servico)
        REFERENCES servico(id_servico)
        ON DELETE RESTRICT
);
CREATE TABLE produto (
    id_produto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    categoria VARCHAR(100),
    preco NUMERIC(10,2) NOT NULL
        CHECK (preco >= 0),
    custo NUMERIC(10,2)
        CHECK (custo >= 0),
    estoque_atual INT NOT NULL DEFAULT 0
        CHECK (estoque_atual >= 0),
    imagem_url VARCHAR(255),
    ativo BOOLEAN DEFAULT TRUE
);

-- Fotos de produto enviadas pelo painel admin (o endereço vai em produto.imagem_url)
CREATE TABLE IF NOT EXISTS produto_imagem (
    id_imagem INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_conteudo VARCHAR(50) NOT NULL,
    conteudo BYTEA NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE curso (
    id_curso INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    carga_horaria INT NOT NULL
        CHECK (carga_horaria > 0),
    preco NUMERIC(10,2) NOT NULL
        CHECK (preco >= 0),
    ativo BOOLEAN DEFAULT TRUE
);

CREATE TABLE material_curso (
    id_material INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso INT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    tipo_arquivo VARCHAR(50),
    arquivo_url VARCHAR(255) NOT NULL,

    CONSTRAINT fk_material_curso
        FOREIGN KEY (id_curso)
        REFERENCES curso(id_curso)
        ON DELETE CASCADE
);

CREATE TABLE cestinha_interesse (
    id_cestinha INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_produto INT NULL,
    id_curso INT NULL,
    adicionado_em TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_cestinha_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_cestinha_produto
        FOREIGN KEY (id_produto)
        REFERENCES produto(id_produto)
        ON DELETE CASCADE,

    CONSTRAINT fk_cestinha_curso
        FOREIGN KEY (id_curso)
        REFERENCES curso(id_curso)
        ON DELETE CASCADE,

    -- Cada item da cestinha deve ser um produto OU um curso
    CONSTRAINT chk_item_unico CHECK (
        (id_produto IS NOT NULL AND id_curso IS NULL)
        OR
        (id_produto IS NULL AND id_curso IS NOT NULL)
    )
);

CREATE TABLE turma (
    id_turma INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_curso INT NOT NULL,
    id_funcionario INT NOT NULL,
    data_inicio TIMESTAMP NOT NULL,
    data_fim TIMESTAMP NOT NULL,
    capacidade_maxima INT NOT NULL
        CHECK (capacidade_maxima > 0),

    CONSTRAINT fk_turma_curso
        FOREIGN KEY (id_curso)
        REFERENCES curso(id_curso)
        ON DELETE RESTRICT,

    CONSTRAINT fk_turma_funcionario
        FOREIGN KEY (id_funcionario)
        REFERENCES usuario(id_usuario)
        ON DELETE RESTRICT,

    CONSTRAINT chk_datas_turma
        CHECK (data_fim > data_inicio)
);

CREATE TABLE matricula (
    id_matricula INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_turma INT NOT NULL,
    data_matricula TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(50) NOT NULL,

    CONSTRAINT fk_matricula_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_matricula_turma
        FOREIGN KEY (id_turma)
        REFERENCES turma(id_turma)
        ON DELETE CASCADE,

    CONSTRAINT uk_usuario_turma
        UNIQUE (id_usuario, id_turma)
);

CREATE TABLE avaliacao (
    id_avaliacao INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    nota INT NOT NULL
        CHECK (nota BETWEEN 1 AND 5),
    comentario TEXT,
    tipo_origem VARCHAR(50),
    referencia_id INT,

    CONSTRAINT fk_avaliacao_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);

-- -----------------------------------------------------
-- Índices
-- (o PostgreSQL não cria índice automático para FKs, por isso eles ajudam)
-- -----------------------------------------------------

-- Obs.: o UNIQUE de usuario.email já cria um índice; este é redundante,
-- mas foi mantido para ficar igual ao script original.
CREATE INDEX idx_usuario_email
    ON usuario(email);

CREATE INDEX idx_usuario_tipo
    ON usuario(tipo);

CREATE INDEX idx_servico_categoria
    ON servico(categoria);

CREATE INDEX idx_produto_categoria
    ON produto(categoria);

CREATE INDEX idx_agendamento_usuario
    ON agendamento(id_usuario);

CREATE INDEX idx_agendamento_servico
    ON agendamento(id_servico);

CREATE INDEX idx_cestinha_usuario
    ON cestinha_interesse(id_usuario);

CREATE INDEX idx_turma_curso
    ON turma(id_curso);

CREATE INDEX idx_turma_funcionario
    ON turma(id_funcionario);

CREATE INDEX idx_matricula_usuario
    ON matricula(id_usuario);

CREATE INDEX idx_matricula_turma
    ON matricula(id_turma);

